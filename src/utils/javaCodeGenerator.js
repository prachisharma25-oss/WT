/**
 * Java Code Generator
 * Converts UML class diagram data into Java source code.
 *
 * HOW IT WORKS:
 * 1. For each class, find its relationships (inheritance, implementation, etc.)
 * 2. Build the class declaration with extends/implements
 * 3. Generate fields with proper access modifiers
 * 4. Generate methods with proper signatures
 * 5. Add getters/setters for private fields
 */

const VISIBILITY_MAP = {
  public: 'public',
  private: 'private',
  protected: 'protected',
  package: '', // package-private = no modifier
}

/**
 * Main entry point — returns a map of { ClassName -> javaSourceCode }
 */
export function generateJavaCode(classes, relationships) {
  const result = {}

  classes.forEach(cls => {
    result[cls.name] = generateClassCode(cls, classes, relationships)
  })

  return result
}

function generateClassCode(cls, allClasses, relationships) {
  const lines = []

  // File header comment
  lines.push(`/**`)
  lines.push(` * ${cls.name}.java`)
  lines.push(` * Generated by UML Studio`)
  lines.push(` * `)
  if (cls.type === 'interface') {
    lines.push(` * UML Interface`)
  } else if (cls.isAbstract) {
    lines.push(` * UML Abstract Class`)
  } else {
    lines.push(` * UML Class`)
  }
  lines.push(` */`)
  lines.push(``)

  // Find relationships for this class
  const outgoing = relationships.filter(r => r.fromId === cls.id)
  const incoming = relationships.filter(r => r.toId === cls.id)

  // Find parent (inheritance)
  const parentRel = outgoing.find(r => r.type === 'inheritance')
  const parentClass = parentRel ? allClasses.find(c => c.id === parentRel.toId) : null

  // Find implemented interfaces
  const implRels = outgoing.filter(r => r.type === 'implementation')
  const interfaces = implRels
    .map(r => allClasses.find(c => c.id === r.toId))
    .filter(Boolean)

  // Find aggregation/composition fields
  const aggRels = outgoing.filter(r => r.type === 'aggregation' || r.type === 'composition')
  const assocRels = outgoing.filter(r => r.type === 'association')

  // Class declaration
  let declaration = ''
  if (cls.type === 'interface') {
    declaration = `public interface ${cls.name}`
    if (interfaces.length > 0) {
      declaration += ` extends ${interfaces.map(i => i.name).join(', ')}`
    }
  } else {
    const modifiers = ['public']
    if (cls.isAbstract) modifiers.push('abstract')
    declaration = `${modifiers.join(' ')} class ${cls.name}`
    if (parentClass) {
      declaration += ` extends ${parentClass.name}`
    }
    if (interfaces.length > 0) {
      declaration += ` implements ${interfaces.map(i => i.name).join(', ')}`
    }
  }

  lines.push(`${declaration} {`)
  lines.push(``)

  if (cls.type !== 'interface') {
    // === FIELDS ===
    if (cls.fields.length > 0 || aggRels.length > 0 || assocRels.length > 0) {
      lines.push(`    // Fields`)

      cls.fields.forEach(field => {
        const vis = VISIBILITY_MAP[field.visibility] ?? field.visibility
        const visStr = vis ? `${vis} ` : ''
        lines.push(`    ${visStr}${field.type} ${field.name};`)
      })

      // Relationship-based fields
      aggRels.forEach(rel => {
        const targetClass = allClasses.find(c => c.id === rel.toId)
        if (targetClass) {
          lines.push(`    private ${targetClass.name} ${lcFirst(targetClass.name)}; // aggregation`)
        }
      })

      assocRels.forEach(rel => {
        const targetClass = allClasses.find(c => c.id === rel.toId)
        if (targetClass) {
          lines.push(`    private ${targetClass.name} ${lcFirst(targetClass.name)}; // association`)
        }
      })

      lines.push(``)
    }

    // === CONSTRUCTOR ===
    const constructorParams = cls.fields
      .filter(f => f.visibility !== 'private')
      .map(f => `${f.type} ${f.name}`)
      .join(', ')

    lines.push(`    // Constructor`)
    lines.push(`    public ${cls.name}(${constructorParams}) {`)

    if (parentClass) {
      lines.push(`        super();`)
    }

    cls.fields
      .filter(f => f.visibility !== 'private')
      .forEach(f => {
        lines.push(`        this.${f.name} = ${f.name};`)
      })

    if (cls.fields.filter(f => f.visibility !== 'private').length === 0 && !parentClass) {
      lines.push(`        // Default constructor`)
    }

    lines.push(`    }`)
    lines.push(``)

    // === GETTERS / SETTERS for private fields ===
    const privateFields = cls.fields.filter(f => f.visibility === 'private')
    if (privateFields.length > 0) {
      lines.push(`    // Getters and Setters`)
      privateFields.forEach(field => {
        const capName = ucFirst(field.name)
        const getBool = field.type === 'boolean' || field.type === 'Boolean'

        // Getter
        lines.push(`    public ${field.type} ${getBool ? 'is' : 'get'}${capName}() {`)
        lines.push(`        return this.${field.name};`)
        lines.push(`    }`)
        lines.push(``)

        // Setter
        lines.push(`    public void set${capName}(${field.type} ${field.name}) {`)
        lines.push(`        this.${field.name} = ${field.name};`)
        lines.push(`    }`)
        lines.push(``)
      })
    }
  }

  // === METHODS ===
  if (cls.methods.length > 0) {
    lines.push(`    // Methods`)
    cls.methods.forEach(method => {
      const vis = VISIBILITY_MAP[method.visibility] ?? method.visibility
      const visStr = vis ? `${vis} ` : ''
      const abstractStr = method.isAbstract ? 'abstract ' : ''
      const staticStr = method.isStatic ? 'static ' : ''

      const signature = `${visStr}${abstractStr}${staticStr}${method.returnType} ${method.name}(${method.params || ''})`

      // Check if this method is overriding parent
      const isOverride = parentClass &&
        parentClass.methods &&
        parentClass.methods.some(pm => pm.name === method.name)

      if (isOverride) {
        lines.push(`    @Override`)
      }

      if (method.isAbstract || cls.type === 'interface') {
        lines.push(`    ${signature};`)
      } else {
        lines.push(`    ${signature} {`)
        // Generate method body based on return type
        const body = generateMethodBody(method)
        body.forEach(b => lines.push(`        ${b}`))
        lines.push(`    }`)
      }
      lines.push(``)
    })
  }

  lines.push(`}`)
  lines.push(``)

  return lines.join('\n')
}

function generateMethodBody(method) {
  const rt = method.returnType
  if (rt === 'void') return ['// TODO: Implement method']
  if (rt === 'int' || rt === 'long' || rt === 'short' || rt === 'byte') return ['return 0;']
  if (rt === 'double' || rt === 'float') return ['return 0.0;']
  if (rt === 'boolean') return ['return false;']
  if (rt === 'char') return ["return '\\0';"]
  if (rt === 'String') return ['return "";']
  return ['return null;']
}

function ucFirst(str) {
  if (!str) return str
  return str.charAt(0).toUpperCase() + str.slice(1)
}

function lcFirst(str) {
  if (!str) return str
  return str.charAt(0).toLowerCase() + str.slice(1)
}
